from django.db import models
from django.conf import settings


class AIAnalysis(models.Model):
    issue = models.OneToOneField(
        'issues.Issue',
        on_delete=models.CASCADE,
        related_name='ai_analysis'
    )
    detected_category = models.ForeignKey(
        'issues.IssueCategory',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='ai_detections'
    )
    recommended_department = models.ForeignKey(
        'departments.Department',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='ai_recommendations'
    )
    suggested_priority = models.CharField(max_length=20, blank=True)
    confidence_score = models.PositiveSmallIntegerField(
        default=85,
        help_text="Advisory confidence score 0-100. Human staff make all binding decisions."
    )
    reasoning = models.TextField(
        blank=True,
        help_text="Reasoning explanation generated by vision/NLP models"
    )
    is_overridden = models.BooleanField(default=False)
    overridden_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='ai_overrides'
    )
    override_reason = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = 'AI Analysis'
        verbose_name_plural = 'AI Analyses'

    def __str__(self):
        return f"AI Suggestion for {self.issue.issue_id} ({self.confidence_score}%)"


class DuplicateMatch(models.Model):
    primary_issue = models.ForeignKey(
        'issues.Issue',
        on_delete=models.CASCADE,
        related_name='duplicate_matches_as_primary'
    )
    matched_issue = models.ForeignKey(
        'issues.Issue',
        on_delete=models.CASCADE,
        related_name='duplicate_matches_as_secondary'
    )
    similarity_score = models.FloatField(default=0.0, help_text="0.0 to 1.0 similarity score")
    distance_meters = models.FloatField(default=0.0, help_text="Distance between issues in meters")
    is_merged = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = 'Duplicate Match'
        verbose_name_plural = 'Duplicate Matches'
        unique_together = ('primary_issue', 'matched_issue')
